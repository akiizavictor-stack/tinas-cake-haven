/**
 * Enqueue the slider script only on the front page.
 */
function tch_hero_slider_assets() {
	if ( ! is_front_page() || is_admin() ) {
		return;
	}
	$path = get_theme_file_path( 'assets/js/hero-slider.js' );
	$ver  = file_exists( $path ) ? (string) filemtime( $path ) : '1.0.0';
	wp_enqueue_script( 'tch-hero-slider', get_theme_file_uri( 'assets/js/hero-slider.js' ), array(), $ver, true );
}
add_action( 'wp_enqueue_scripts', 'tch_hero_slider_assets' );

/**
 * Preload the first slide image so the hero paints fast with no layout shift.
 */
function tch_hero_slider_preload() {
	if ( ! is_front_page() || is_admin() ) {
		return;
	}
	$slides = tch_hero_slider_slides();
	if ( empty( $slides[0]['url'] ) ) {
		return;
	}
	printf( '<link rel="preload" as="image" href="%s" fetchpriority="high">' . "\n", esc_url( $slides[0]['url'] ) );
}
add_action( 'wp_head', 'tch_hero_slider_preload', 2 );

/**
 * Replace the generated `tch-hero` group block with the slider on the front page.
 *
 * @param string $block_content Rendered block HTML.
 * @param array  $block         Parsed block.
 * @return string
 */
function tch_hero_slider_render_block( $block_content, $block ) {
	if ( is_admin() || ! is_front_page() ) {
		return $block_content;
	}
	if ( 'core/group' !== $block['blockName'] ) {
		return $block_content;
	}
	$cls = isset( $block['attrs']['className'] ) ? $block['attrs']['className'] : '';
	if ( false === strpos( $cls, 'tch-hero' ) ) {
		return $block_content;
	}
	static $done = false;
	if ( $done ) {
		return $block_content;
	}
	$done = true;
	return tch_render_hero_slider();
}
add_filter( 'render_block', 'tch_hero_slider_render_block', 10, 2 );
