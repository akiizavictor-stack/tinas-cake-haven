/**
 * Theme setup.
 */
function tch_theme_setup() {
	add_editor_style( 'style.css' );
	add_theme_support( 'responsive-embeds' );
	add_theme_support( 'elementor' );
	add_theme_support( 'header-footer-elementor' );
	register_block_style( 'core/button', array( 'name' => 'whatsapp', 'label' => __( 'WhatsApp', 'tinas-cake-haven' ) ) );
	// Remove parent patterns we do not use, keeping the inserter focused on the brand.
	remove_theme_support( 'core-block-patterns' );

	register_nav_menus( array(
		'primary'     => __( 'Primary Navigation', 'tinas-cake-haven' ),
		'footer_shop' => __( 'Footer Shop Menu', 'tinas-cake-haven' ),
		'footer_info' => __( 'Footer Info Menu', 'tinas-cake-haven' ),
	) );
}
add_action( 'after_setup_theme', 'tch_theme_setup' );

/**
 * Styles.
 */
function tch_theme_assets() {
	// Version = file modification time, so browsers and caches pick up every change.
	wp_enqueue_style( 'tinas-cake-haven', get_stylesheet_uri(), array(), (string) filemtime( get_stylesheet_directory() . '/style.css' ) );
}
add_action( 'wp_enqueue_scripts', 'tch_theme_assets' );

/**
 * Enqueue theme styles inside Elementor editor preview.
 */
function tch_theme_elementor_editor_styles() {
	wp_enqueue_style( 'tinas-cake-haven-editor', get_stylesheet_uri(), array(), (string) filemtime( get_stylesheet_directory() . '/style.css' ) );
}
add_action( 'elementor/editor/after_enqueue_styles', 'tch_theme_elementor_editor_styles' );
add_action( 'elementor/preview/enqueue_styles', 'tch_theme_elementor_editor_styles' );

/**
 * Preload the two fonts used above the fold.
 */
function tch_theme_preload_fonts() {
	foreach ( array( 'nunito-variable.woff2', 'playfair-display-700.woff2' ) as $font ) {
		printf( '<link rel="preload" href="%s" as="font" type="font/woff2" crossorigin>' . "\n", esc_url( get_theme_file_uri( 'assets/fonts/' . $font ) ) );
	}
}
add_action( 'wp_head', 'tch_theme_preload_fonts', 1 );

/**
 * Connects the header/footer navigation blocks to the menus created by the setup tool.
 * The template parts mark them with a class; the menu post ids are stored in options,
 * so the owner can still edit the menus under Appearance → Editor → Navigation.
 *
 * @param array $block Parsed block.
 * @return array
 */
function tch_theme_navigation_refs( $block ) {
	if ( 'core/navigation' !== $block['blockName'] || ! empty( $block['attrs']['ref'] ) ) {
		return $block;
	}
	$class = $block['attrs']['className'] ?? '';
	$map   = array( 'tch-nav-main' => 'tch_nav_main', 'tch-nav-footer' => 'tch_nav_footer', 'tch-nav-legal' => 'tch_nav_legal' );
	foreach ( $map as $css => $option ) {
		if ( false !== strpos( $class, $css ) ) {
			$id = (int) get_option( $option );
			if ( $id && 'publish' === get_post_status( $id ) ) {
				$block['attrs']['ref'] = $id;
			}
		}
	}
	return $block;
}
add_filter( 'render_block_data', 'tch_theme_navigation_refs' );

/**
 * Uses the business logo as the site logo when none is set.
 *
 * @param string $html Logo HTML.
 * @return string
 */
function tch_theme_fallback_logo( $html ) {
	if ( $html ) {
		return $html;
	}
	return sprintf(
		'<a href="%1$s" class="custom-logo-link" rel="home"><img src="%2$s" class="custom-logo" alt="%3$s" width="256" height="256" decoding="async"></a>',
		esc_url( home_url( '/' ) ),
		esc_url( get_theme_file_uri( 'assets/images/logo-256.webp' ) ),
		esc_attr( get_bloginfo( 'name' ) )
	);
}
add_filter( 'get_custom_logo', 'tch_theme_fallback_logo' );

/**
 * Floating WhatsApp button on every page.
 */
function tch_theme_floating_whatsapp() {
	if ( ! function_exists( 'tch_whatsapp_link' ) ) {
		return;
	}
	printf(
		'<a class="tch-float-wa" href="%1$s" target="_blank" rel="noopener" aria-label="%2$s"><img src="%3$s" alt="" width="30" height="30"></a>',
		esc_url( tch_whatsapp_link( "Hello Tina's Cake Haven, I would like to ask about a cake." ) ),
		esc_attr__( 'Chat with us on WhatsApp', 'tinas-cake-haven' ),
		esc_url( get_theme_file_uri( 'assets/images/whatsapp.svg' ) )
	);
}
add_action( 'wp_footer', 'tch_theme_floating_whatsapp' );


/**
 * ---------------------------------------------------------------------------
 * Homepage hero image slider
 *
 * The homepage hero is a Gutenberg `core/group` block (className `tch-hero`)
 * generated by the core plugin's setup tool and stored on the `home` page.
 * Instead of editing the database (which a setup re-run would overwrite), the
 * slider is swapped in at render time on the front page only, leaving every
 * other page and every other homepage section untouched. Disabling the
 * filter below restores the original two-column hero.
 *
 * Slides are managed from wp-admin → Hero Slider (see the "Tina's Cake Haven
 * Core" plugin) and read here via tch_hero_slider_slides().
 * ---------------------------------------------------------------------------
 */

/**
 * Resolves the hero slider slides for the front page.
 *
 * Uses the Hero Slider dashboard settings (Tina's Cake Haven Core plugin) when
 * slides are configured, otherwise falls back to the built-in default bakery
 * photos so the homepage never breaks – even if the plugin is deactivated.
 *
 * @return array<int,array{id:int,width:int,height:int,url:string,alt:string,srcset:string}>
 */
function tch_hero_slider_slides() {
	if ( class_exists( 'TCH_Hero_Slider' ) ) {
		$slides = TCH_Hero_Slider::get_slides();
		if ( ! empty( $slides ) ) {
			return $slides;
		}
	}
	// Ultimate fallback: the original five hero photographs (URL-based).
	$uploads = wp_get_upload_dir();
	$base    = isset( $uploads['baseurl'] ) ? trailingslashit( $uploads['baseurl'] ) . '2026/11/' : home_url( '/wp-content/uploads/2026/11/' );
	return array(
		array( 'id' => 0, 'url' => $base . 'hero-chocolate-happy-birthday-cake-1536x1229.webp', 'width' => 1536, 'height' => 1229, 'alt' => 'Chocolate drip birthday cake with piped rosettes and Happy Birthday writing', 'srcset' => '' ),
		array( 'id' => 0, 'url' => $base . 'floral-happy-birthday-cake-1536x1152.webp', 'width' => 1536, 'height' => 1152, 'alt' => 'White birthday cake decorated with pink and yellow buttercream roses', 'srcset' => '' ),
		array( 'id' => 0, 'url' => $base . 'stock-flower-topped-small-cake-1536x1023.webp', 'width' => 1536, 'height' => 1023, 'alt' => 'Small birthday cake decorated with fresh flowers', 'srcset' => '' ),
		array( 'id' => 0, 'url' => $base . 'vanilla-cupcakes-with-sprinkles-1024x1536.webp', 'width' => 1024, 'height' => 1536, 'alt' => 'Vanilla cupcakes with swirled white frosting and rainbow sprinkles', 'srcset' => '' ),
		array( 'id' => 0, 'url' => $base . 'chocolate-chip-cookies-on-plate-768x768.webp', 'width' => 768, 'height' => 768, 'alt' => 'Plate of freshly baked chocolate chip cookies', 'srcset' => '' ),
	);
}

